// IndexEntry is one package in the index; it is built from what was written, so
// the index cannot drift from the package.
type IndexEntry struct {
	Name        string
	Version     string
	Arch        string
	Size        int64
	Installed   int64
	ControlSHA  string
	Description string
	URL         string
	License     string
	Maintainer  string
	BuildTime   int64
	Depends     []string
	Provides    []string
	Replaces    []string
}

// EntryFromManifest makes the index record for a built package.
func EntryFromManifest(m *Manifest, r *BuildResult, when time.Time) IndexEntry {
	return IndexEntry{
		Name:        m.Name,
		Version:     m.FullVersion(),
		Arch:        m.Arch,
		Size:        r.Size,
		Installed:   r.Installed,
		ControlSHA:  r.ControlSHA,
		Description: m.Description,
		URL:         m.URL,
		License:     m.License,
		Maintainer:  m.Maintainer,
		BuildTime:   when.Unix(),
		Depends:     m.Depends,
		Provides:    m.Provides,
		Replaces:    m.Replaces,
	}
}

// WriteIndex builds APKINDEX.tar.gz, signed when keyPath is set.
func WriteIndex(entries []IndexEntry, outPath, keyPath string) (int64, error) {
	var b strings.Builder
	for _, e := range entries {
		fmt.Fprintf(&b, "C:%s\n", e.ControlSHA)
		fmt.Fprintf(&b, "P:%s\n", e.Name)
		fmt.Fprintf(&b, "V:%s\n", e.Version)
		fmt.Fprintf(&b, "A:%s\n", e.Arch)
		fmt.Fprintf(&b, "S:%d\n", e.Size)
		fmt.Fprintf(&b, "I:%d\n", e.Installed)
		if e.Description != "" {
			fmt.Fprintf(&b, "T:%s\n", e.Description)
		}
		if e.URL != "" {
			fmt.Fprintf(&b, "U:%s\n", e.URL)
		}
		if e.License != "" {
			fmt.Fprintf(&b, "L:%s\n", e.License)
		}
		fmt.Fprintf(&b, "o:%s\n", e.Name)
		if e.Maintainer != "" {
			fmt.Fprintf(&b, "m:%s\n", e.Maintainer)
		}
		fmt.Fprintf(&b, "t:%d\n", e.BuildTime)
		if len(e.Depends) > 0 {
			fmt.Fprintf(&b, "D:%s\n", strings.Join(e.Depends, " "))
		}
		if len(e.Provides) > 0 {
			fmt.Fprintf(&b, "p:%s\n", strings.Join(e.Provides, " "))
		}
		if len(e.Replaces) > 0 {
			fmt.Fprintf(&b, "r:%s\n", strings.Join(e.Replaces, " "))
		}
		b.WriteString("\n")
	}
	when := time.Now()
	indexStream, err := stream(map[string][]byte{
		"APKINDEX":    []byte(b.String()),
		"DESCRIPTION": []byte("akmesh package repository\n"),
	}, when)
	if err != nil {
		return 0, err
	}
	body := indexStream
	if keyPath != "" {
		sig, name, err := sign(keyPath, body)
		if err != nil {
			return 0, err
		}
		sigStream, err := streamNoEnd(map[string][]byte{name: sig}, when)
		if err != nil {
			return 0, err
		}
		body = append(sigStream, body...)
	}
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		return 0, err
	}
	if err := os.WriteFile(outPath, body, 0o644); err != nil {
		return 0, err
	}
	return int64(len(body)), nil
}

// ReadIndexFile reads an existing index entry set, so "index" can add to what is
// already there instead of replacing it.
func ReadIndexFile(path string) ([]IndexEntry, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	entries := map[string]IndexEntry{} // key: name-version, so versions coexist
	var cur *IndexEntry
	flush := func() {
		if cur != nil && cur.Name != "" {
			entries[cur.Name+"-"+cur.Version] = *cur
		}
		cur = nil
	}
	var fields map[string]string
	for line := range strings.SplitSeq(decompress(data), "\n") {
		if line == "" {
			if cur != nil && fields != nil {
				cur.ControlSHA = fields["C"]
				cur.Name = fields["P"]
				cur.Version = fields["V"]
				cur.Arch = fields["A"]
				cur.Size = atoi(fields["S"])
				cur.Installed = atoi(fields["I"])
				cur.Description = fields["T"]
				cur.URL = fields["U"]
				cur.License = fields["L"]
				cur.Maintainer = fields["m"]
				cur.BuildTime = atoi64(fields["t"])
				cur.Depends = strings.Fields(fields["D"])
				cur.Provides = strings.Fields(fields["p"])
				cur.Replaces = strings.Fields(fields["r"])
			}
			flush()
			fields = nil
			continue
		}
		if len(line) < 2 || line[1] != ':' {
			continue
		}
		if cur == nil {
			cur = &IndexEntry{}
		}
		if fields == nil {
			fields = map[string]string{}
		}
		fields[line[:1]] = line[2:]
	}
	flush()
	out := make([]IndexEntry, 0, len(entries))
	for _, e := range entries {
		out = append(out, e)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

func atoi(s string) int64 { return atoi64(s) }
func atoi64(s string) int64 {
	n, _ := strconv.ParseInt(s, 10, 64)
	return n
}

// decompress pulls the APKINDEX text out of a (possibly signed) index archive.
func decompress(data []byte) string {
	var out strings.Builder
	pos := 0
	for pos < len(data) {
		hdrLen, err := apkcore.HeaderLen(data[pos:])
		if err != nil {
			break
		}
		body, used, err := apkcore.Inflate(data[pos+hdrLen:])
		if err != nil {
			break
		}
		pos += hdrLen + used + 8
		tr := tar.NewReader(bytes.NewReader(body))
		for {
			h, err := tr.Next()
			if err != nil {
				break
			}
			if h.Name == "APKINDEX" {
				content, _ := io.ReadAll(tr)
				out.Write(content)
			}
		}
	}
	return out.String()
}
