// Package apkbuild builds apk packages and repository indexes in Go, the
// counterpart to internal/apkcore. It writes what internal/apkcore reads and
// what apk-tools accepts, without abuild and without a shell recipe.
//
// Measured format (docs/measurements.md):
//
//	.apk             signature member (optional), control member, data member
//	C:Q1... in index sha1 over the RAW control member, base64
//	.PKGINFO         carries datahash = sha256 of the RAW data member, hex
//	signature        RSA PKCS1v15 with SHA1 over everything after it
//
// SHA1 is not a shortcut: apk names that block .SIGN.RSA.<key> and verifies it,
// while SHA256 lives in a .SIGN.RSA256.<key> block of a newer format.
package apkbuild

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"crypto"
	"crypto/rand"
	"crypto/rsa"
	"crypto/sha1"
	"crypto/sha256"
	"crypto/x509"
	"encoding/base64"
	"encoding/hex"
	"encoding/pem"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"

	"akmesh/internal/winmode"
	"strconv"
	"strings"
	"time"

	"akmesh/internal/apkcore"
)

// Manifest is what a package says about itself. The file uses "key = value"
// lines, the same shape as .PKGINFO, so an agent can read and write it without
// a second syntax to learn.
type Manifest struct {
	Name        string
	Version     string
	Release     string
	Description string
	URL         string
	License     string
	Maintainer  string
	Arch        string
	Depends     []string
	Provides    []string
	Replaces    []string
	Triggers    []string
	Scripts     map[string]string // ".post-install" -> file on disk
	// SourceDateEpoch fixes every timestamp. Zero means "the current time",
	// which is what a non-reproducible build does.
	SourceDateEpoch int64
}

// ReadManifest parses a manifest file.
func ReadManifest(path string) (*Manifest, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	m := &Manifest{Arch: "x86_64", Release: "0", Scripts: map[string]string{}}
	for n, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.SplitN(line, "=", 2)
		if len(parts) != 2 {
			return nil, fmt.Errorf("%s:%d: expected \"key = value\"", path, n+1)
		}
		key := strings.ToLower(strings.TrimSpace(parts[0]))
		val := strings.TrimSpace(parts[1])
		switch key {
		case "pkgname":
			m.Name = val
		case "pkgver":
			m.Version = val
		case "pkgrel":
			m.Release = val
		case "pkgdesc":
			m.Description = val
		case "url":
			m.URL = val
		case "license":
			m.License = val
		case "maintainer":
			m.Maintainer = val
		case "arch":
			m.Arch = val
		case "depends":
			m.Depends = strings.Fields(val)
		case "provides":
			m.Provides = strings.Fields(val)
		case "replaces":
			m.Replaces = strings.Fields(val)
		case "triggers":
			m.Triggers = strings.Fields(val)
		case "source_date_epoch":
			n, err := strconv.ParseInt(val, 10, 64)
			if err != nil {
				return nil, fmt.Errorf("%s:%d: bad source_date_epoch", path, n+1)
			}
			m.SourceDateEpoch = n
		case "script":
			// script = .post-install:scripts/post-install
			s := strings.SplitN(val, ":", 2)
			if len(s) != 2 {
				return nil, fmt.Errorf("%s:%d: script needs NAME:PATH", path, n+1)
			}
			m.Scripts[s[0]] = s[1]
		default:
			return nil, fmt.Errorf("%s:%d: unknown key %q", path, n+1, key)
		}
	}
	if m.Name == "" || m.Version == "" {
		return nil, fmt.Errorf("%s: pkgname and pkgver are required", path)
	}
	return m, nil
}

// FullVersion is what the file name and the index carry: 0.0.1-r0.
func (m *Manifest) FullVersion() string {
	rel := m.Release
	if rel == "" {
		rel = "0"
	}
	return m.Version + "-r" + rel
}

// FileName is the package file name.
func (m *Manifest) FileName() string {
	return fmt.Sprintf("%s-%s.apk", m.Name, m.FullVersion())
}

// BuildResult tells the caller what it wrote.
type BuildResult struct {
	Path       string
	Size       int64
	Installed  int64
	ControlSHA string // Q1... which the index repeats
	DataSHA    string // datahash
}

// Build writes one package from a directory tree.
func Build(m *Manifest, sourceDir, outDir, keyPath string) (*BuildResult, error) {
	when := time.Unix(m.SourceDateEpoch, 0)
	if m.SourceDateEpoch == 0 {
		when = time.Now()
	}
	data, installed, err := dataStream(sourceDir, when)
	if err != nil {
		return nil, err
	}
	dataSum := sha256.Sum256(data)

	pkginfo := &bytes.Buffer{}
	fmt.Fprintf(pkginfo, "# Generated by akmesh apkbuild\n")
	fmt.Fprintf(pkginfo, "pkgname = %s\n", m.Name)
	fmt.Fprintf(pkginfo, "pkgver = %s\n", m.FullVersion())
	if m.Description != "" {
		fmt.Fprintf(pkginfo, "pkgdesc = %s\n", m.Description)
	}
	if m.URL != "" {
		fmt.Fprintf(pkginfo, "url = %s\n", m.URL)
	}
	fmt.Fprintf(pkginfo, "builddate = %d\n", when.Unix())
	if m.Maintainer != "" {
		fmt.Fprintf(pkginfo, "packager = %s\n", m.Maintainer)
	}
	fmt.Fprintf(pkginfo, "size = %d\n", installed)
	fmt.Fprintf(pkginfo, "arch = %s\n", m.Arch)
	fmt.Fprintf(pkginfo, "origin = %s\n", m.Name)
	if m.License != "" {
		fmt.Fprintf(pkginfo, "license = %s\n", m.License)
	}
	if len(m.Depends) > 0 {
		fmt.Fprintf(pkginfo, "depend = %s\n", strings.Join(m.Depends, " "))
	}
	if len(m.Provides) > 0 {
		fmt.Fprintf(pkginfo, "provides = %s\n", strings.Join(m.Provides, " "))
	}
	if len(m.Replaces) > 0 {
		fmt.Fprintf(pkginfo, "replaces = %s\n", strings.Join(m.Replaces, " "))
	}
	if len(m.Triggers) > 0 {
		fmt.Fprintf(pkginfo, "triggers = %s\n", strings.Join(m.Triggers, " "))
	}
	fmt.Fprintf(pkginfo, "datahash = %x\n", dataSum)

	controlFiles := map[string][]byte{".PKGINFO": pkginfo.Bytes()}
	for name, path := range m.Scripts {
		body, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("script %s: %v", name, err)
		}
		controlFiles[name] = body
	}
	// No tar end-of-archive blocks in the control member: apk's tar parser
	// reads all gzip members as one tar stream and a second zero block makes it
	// mistake the next member's first block for a header (-74 BAD archive).
	// abuild does the same with "abuild-tar --cut" (measured 24.11.2026).
	control, err := streamNoEnd(controlFiles, when)
	if err != nil {
		return nil, err
	}

	body := append(append([]byte{}, control...), data...)
	if keyPath != "" {
		// A package signature covers the CONTROL member only; the data is tied
		// in through datahash inside the signed .PKGINFO. Measured: the RSA
		// block of an abuild package decrypts to sha1(control) exactly, and
		// signing control+data makes apk answer "BAD signature" (24.11.2026).
		sig, name, err := sign(keyPath, control)
		if err != nil {
			return nil, err
		}
		sigStream, err := streamNoEnd(map[string][]byte{name: sig}, when)
		if err != nil {
			return nil, err
		}
		body = append(sigStream, body...)
	}

	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return nil, err
	}
	path := filepath.Join(outDir, m.FileName())
	if err := os.WriteFile(path, body, 0o644); err != nil {
		return nil, err
	}
	return &BuildResult{
		Path:       path,
		Size:       int64(len(body)),
		Installed:  installed,
		ControlSHA: "Q1" + base64.StdEncoding.EncodeToString(sha1Sum(control)),
		DataSHA:    fmt.Sprintf("%x", dataSum),
	}, nil
}

func sha1Sum(b []byte) []byte {
	s := sha1.Sum(b)
	return s[:]
}

// dataStream packs a directory tree into one gzip member. Paths are relative
// and slash-separated, directories end with "/" - exactly what apk extracts.
func dataStream(dir string, when time.Time) ([]byte, int64, error) {
	files := map[string][]byte{}
	modes := map[string]int64{}
	links := map[string]string{}
	kinds := map[string]byte{}
	var installed int64

	root := filepath.Clean(dir)
	err := filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if path == root {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		name := filepath.ToSlash(rel)
		mode := int64(info.Mode().Perm())
		// On Windows the platform has no bits; our chmod records them in the ACL
		// and that record is what a package built there must carry.
		if m, ok := winmode.Get(path); ok {
			mode = int64(m.Perm())
		}
		switch {
		case info.IsDir():
			files[name+"/"] = nil
			modes[name+"/"] = mode | 0o40000
			kinds[name+"/"] = tar.TypeDir
		case info.Mode()&os.ModeSymlink != 0:
			target, err := os.Readlink(path)
			if err != nil {
				return err
			}
			links[name] = target
			// A symlink carries no body, but it must appear in files or the tar
			// loop never sees it (found on 24.11.2026: links were dropped silently).
			files[name] = nil
			modes[name] = mode | 0o120000
			kinds[name] = tar.TypeSymlink
		default:
			body, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			files[name] = body
			modes[name] = mode
			kinds[name] = tar.TypeReg
			installed += int64(len(body))
		}
		return nil
	})
	if err != nil {
		return nil, 0, err
	}

	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)

	var buf bytes.Buffer
	zw := gzip.NewWriter(&buf)
	zw.Header.ModTime = when
	tw := tar.NewWriter(zw)
	for _, name := range names {
		hdr := &tar.Header{
			Name:    name,
			Mode:    modes[name] & 0o7777,
			ModTime: when,
			Format:  tar.FormatPAX,
		}
		// apk-tools 3 refuses files without an embedded checksum ("file format
		// is obsolete", measured with 3.0.9). abuild writes this PAX record for
		// every regular file; 2.x ignores it.
		if kinds[name] == tar.TypeReg {
			sum := sha1.Sum(files[name])
			hdr.PAXRecords = map[string]string{"APK-TOOLS.checksum.SHA1": hex.EncodeToString(sum[:])}
		}
		switch kinds[name] {
		case tar.TypeDir:
			hdr.Typeflag = tar.TypeDir
		case tar.TypeSymlink:
			hdr.Typeflag = tar.TypeSymlink
			hdr.Linkname = links[name]
		default:
			hdr.Typeflag = tar.TypeReg
			hdr.Size = int64(len(files[name]))
		}
		if err := tw.WriteHeader(hdr); err != nil {
			return nil, 0, err
		}
		if hdr.Typeflag == tar.TypeReg {
			if _, err := tw.Write(files[name]); err != nil {
				return nil, 0, err
			}
		}
	}
	if err := tw.Close(); err != nil {
		return nil, 0, err
	}
	if err := zw.Close(); err != nil {
		return nil, 0, err
	}
	return buf.Bytes(), installed, nil
}

// stream packs control files into one gzip member, sorted, so two builds of the
// same input are byte-identical.
func stream(files map[string][]byte, when time.Time) ([]byte, error) {
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	var buf bytes.Buffer
	zw := gzip.NewWriter(&buf)
	zw.Header.ModTime = when
	tw := tar.NewWriter(zw)
	for _, name := range names {
		hdr := &tar.Header{
			Name:     name,
			Mode:     0o644,
			Size:     int64(len(files[name])),
			ModTime:  when,
			Typeflag: tar.TypeReg,
			Format:   tar.FormatPAX,
		}
		if strings.HasPrefix(name, ".") && name != ".PKGINFO" {
			hdr.Mode = 0o755 // install scripts are executed
		}
		if err := tw.WriteHeader(hdr); err != nil {
			return nil, err
		}
		if _, err := tw.Write(files[name]); err != nil {
			return nil, err
		}
	}
	if err := tw.Close(); err != nil {
		return nil, err
	}
	if err := zw.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// streamNoEnd packs control files into one gzip member and drops the tar
// end-of-archive blocks. apk rejects a signature member that carries them
// ("BAD archive", measured 24.11.2026): bsdtar writes the signature tar without
// zeros, and only that shape is accepted. The control and data members keep
// their blocks; apk takes them.
func streamNoEnd(files map[string][]byte, when time.Time) ([]byte, error) {
	full, err := stream(files, when)
	if err != nil {
		return nil, err
	}
	// gunzip, trim, gzip again: the padding is 1024 zero bytes at the end.
	zr, err := gzip.NewReader(bytes.NewReader(full))
	if err != nil {
		return nil, err
	}
	plain, err := io.ReadAll(zr)
	if err != nil {
		return nil, err
	}
	trimmed := bytes.TrimRight(plain, "\x00")
	// A tar entry always ends on a 512-byte boundary; keep the last block.
	if r := len(trimmed) % 512; r != 0 {
		trimmed = trimmed[:len(trimmed)+(512-r)]
	} else if len(trimmed) < len(plain) {
		trimmed = trimmed[:len(trimmed)]
	}
	var buf bytes.Buffer
	zw := gzip.NewWriter(&buf)
	zw.Header.ModTime = when
	if _, err := zw.Write(trimmed); err != nil {
		return nil, err
	}
	if err := zw.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// ---- keys and signing -----------------------------------------------------

// KeyPair is one RSA key as apk keeps it: PEM private key on disk, public key
// beside it with .pub appended, which is also the name a signature refers to.
type KeyPair struct {
	Private *rsa.PrivateKey
	Name    string // base name with .pub, e.g. builder.rsa.pub
}

// GenerateKey creates an RSA key pair and writes both halves.
func GenerateKey(path string, bits int) (*KeyPair, error) {
	if bits == 0 {
		bits = 2048
	}
	key, err := rsa.GenerateKey(rand.Reader, bits)
	if err != nil {
		return nil, err
	}
	privPEM := pem.EncodeToMemory(&pem.Block{Type: "RSA PRIVATE KEY", Bytes: x509.MarshalPKCS1PrivateKey(key)})
	if err := os.WriteFile(path, privPEM, 0o600); err != nil {
		return nil, err
	}
	pubDER, err := x509.MarshalPKIXPublicKey(&key.PublicKey)
	if err != nil {
		return nil, err
	}
	pubPEM := pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: pubDER})
	pubPath := path + ".pub"
	if err := os.WriteFile(pubPath, pubPEM, 0o644); err != nil {
		return nil, err
	}
	return &KeyPair{Private: key, Name: filepath.Base(pubPath)}, nil
}

// LoadKey reads a PEM private key.
func LoadKey(path string) (*KeyPair, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	block, _ := pem.Decode(data)
	if block == nil {
		return nil, fmt.Errorf("%s: not a PEM key", path)
	}
	key, err := x509.ParsePKCS1PrivateKey(block.Bytes)
	if err != nil {
		if k8, err2 := x509.ParsePKCS8PrivateKey(block.Bytes); err2 == nil {
			if rk, ok := k8.(*rsa.PrivateKey); ok {
				return &KeyPair{Private: rk, Name: filepath.Base(path) + ".pub"}, nil
			}
		}
		return nil, fmt.Errorf("%s: not an RSA private key", path)
	}
	return &KeyPair{Private: key, Name: filepath.Base(path) + ".pub"}, nil
}

// sign returns the signature block name and the raw RSA block over body.
func sign(keyPath string, body []byte) ([]byte, string, error) {
	kp, err := LoadKey(keyPath)
	if err != nil {
		return nil, "", err
	}
	sum := sha1.Sum(body)
	sig, err := rsa.SignPKCS1v15(rand.Reader, kp.Private, crypto.SHA1, sum[:])
	if err != nil {
		return nil, "", err
	}
	return sig, ".SIGN.RSA." + kp.Name, nil
}

